"""Write PROGRESS.md from the phase checklists in TODO.md."""

import re
import sys
from dataclasses import dataclass
from pathlib import Path

BASE_DIR = Path(__file__).parent
TODO_PATH = BASE_DIR / "TODO.md"
PROGRESS_PATH = BASE_DIR / "PROGRESS.md"

BAR_WIDTH = 20
PHASE_PREFIX = "## Phase "
CHECKBOX = re.compile(r"^\s*- \[([ xX])\]")


@dataclass
class Phase:
    """Checkbox counts for one phase section of TODO.md."""

    title: str
    done: int = 0
    total: int = 0

    @property
    def complete(self) -> bool:
        """Return True when the phase has checkboxes and all are checked."""
        return self.total > 0 and self.done == self.total


def parse_phases(text: str) -> list[Phase]:
    """Count checkboxes inside each phase section of the given Markdown."""
    phases: list[Phase] = []
    current: Phase | None = None
    for line in text.splitlines():
        if line.startswith(("# ", "## ")):
            current = None
            if line.startswith(PHASE_PREFIX):
                current = Phase(line.removeprefix("## ").strip())
                phases.append(current)
        elif current is not None:
            match = CHECKBOX.match(line)
            if match:
                current.total += 1
                if match.group(1) != " ":
                    current.done += 1
    return phases


def percent(done: int, total: int) -> int:
    """Return completion as a whole number, rounded down."""
    return done * 100 // total if total else 0


def bar(done: int, total: int) -> str:
    """Return a fixed-width bar with filled cells for done items."""
    filled = BAR_WIDTH * done // total if total else 0
    return "█" * filled + "░" * (BAR_WIDTH - filled)


def summary(done: int, total: int) -> str:
    """Format counts as done/total (percent%)."""
    return f"{done}/{total} ({percent(done, total)}%)"


def render_report(phases: list[Phase]) -> str:
    """Build the Markdown progress report."""
    done = sum(phase.done for phase in phases)
    total = sum(phase.total for phase in phases)
    complete = sum(phase.complete for phase in phases)
    lines = [
        "# Progress",
        "",
        "Generated by `python progress.py` from TODO.md.",
        "",
        f"Overall: {bar(done, total)} {summary(done, total)}",
        "",
        f"Phases complete: {complete}/{len(phases)}",
        "",
        "| Phase | Progress | Done |",
        "| --- | --- | --- |",
    ]
    lines.extend(
        f"| {phase.title} | {bar(phase.done, phase.total)} "
        f"| {summary(phase.done, phase.total)} |"
        for phase in phases
    )
    return "\n".join(lines) + "\n"


def main() -> int:
    """Read TODO.md, write PROGRESS.md and print the report."""
    if not TODO_PATH.is_file():
        print(f"Cannot find {TODO_PATH}", file=sys.stderr)
        return 1
    report = render_report(parse_phases(TODO_PATH.read_text(encoding="utf-8")))
    PROGRESS_PATH.write_text(report, encoding="utf-8")
    print(report, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
